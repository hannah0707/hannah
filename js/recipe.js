  // 把原始数组转成标准对象，并补上运行时字段
  function buildPreset() {
    return PRESET_RAW.map(function (row, i) {
      return {
        id: 'r' + String(i + 1).padStart(3, '0'), // r001, r002 ...
        name: row[0],
        category: row[1],
        difficulty: row[2],
        cookTime: row[3],
        calories: row[4],                  // 卡路里（kcal/份）
        ingredients: row[5].map(function (g) { return [g[0], g[1]]; }),
        steps: row[6].slice(),
        tips: row[7] || '',
        isFavorite: false,
        cookedCount: 0,
        lastCooked: null,
        isCustom: false
      };
    });
  }

  // —— 存储读写 ——
  function load() {
    try {
      var raw = localStorage.getItem(STORE_KEY);
      if (raw) {
        var arr = JSON.parse(raw);
        if (Array.isArray(arr) && arr.length) return arr;
      }
    } catch (e) {}
    var seed = buildPreset();
    save(seed);
    return seed;
  }
  function save(list) {
    try { localStorage.setItem(STORE_KEY, JSON.stringify(list)); } catch (e) {}
  }

  // 内存缓存（首次加载时种子化）
  var cache = load();

  function uid() {
    return 'rc_' + Date.now().toString(36) + Math.random().toString(36).slice(2, 7);
  }
  function todayStr() {
    var d = new Date();
    return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
  }

  // —— 对外 API ——
  function getAll() { return cache; }
  function getById(id) { return cache.find(function (x) { return x.id === id; }) || null; }

  function toggleFav(id) {
    var it = getById(id);
    if (!it) return false;
    it.isFavorite = !it.isFavorite;
    save(cache);
    return it.isFavorite;
  }

  // 记录做过：cookedCount +1，lastCooked 更新为今天
  function recordCook(id) {
    var it = getById(id);
    if (!it) return;
    it.cookedCount = (it.cookedCount || 0) + 1;
    it.lastCooked = todayStr();
    save(cache);
    return it;
  }

  // 按菜名或食材搜索（不区分大小写，包含匹配）
  function search(items, q) {
    q = (q || '').trim().toLowerCase();
    if (!q) return items;
    return items.filter(function (x) {
      if (x.name.toLowerCase().indexOf(q) >= 0) return true;
      return (x.ingredients || []).some(function (g) { return g[0].toLowerCase().indexOf(q) >= 0; });
    });
  }

